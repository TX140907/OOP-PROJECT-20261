package sanbaka.model;

/** Chim chướng ngại vật trên không ở chặng bay trực thăng. */
public class Bird {
    public double x, y, vx, phase;

    public Bird(double x, double y, double vx, double phase) {
        this.x = x;
        this.y = y;
        this.vx = vx;
        this.phase = phase;
    }
}

